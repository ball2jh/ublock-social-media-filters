#!/usr/bin/env node
// Generate userContent.css from the uBO filter list.
//
// Cosmetic rules that are plain CSS become a user stylesheet, which Firefox
// applies itself -- uBO's power button cannot switch it off. Rules using uBO's
// procedural selectors have no CSS equivalent and are reported as skipped.
const fs = require('fs');
const path = require('path');
const { readRules } = require('./read-rules');

const OUT = path.join(__dirname, 'userContent.css');

// uBO procedural pseudos with no CSS equivalent.
const UNTRANSLATABLE =
  /:(has-text|matches-css|matches-media|matches-attr|min-text-length|upward|watch-attr|xpath|others|shadow|spath)\(/;

const MATCHES_PATH = /^:matches-path\(\/(.+?)\/[a-z]*\)/;

// Translate the path-anchored regexes uBO's :matches-path() takes into
// @-moz-document conditions. Only literal paths convert; anything with real
// regex machinery (lookaheads, classes, quantifiers) returns null and the rule
// is reported as skipped.
function pathConditions(re) {
  if (!re.startsWith("^")) return null;
  let body = re.slice(1);
  const anchored = body.endsWith("$");
  if (anchored) body = body.slice(0, -1);

  // A single optional literal group, as in ^\/(home)?$ -> "/" and "/home".
  const optional = /^((?:\\\/|[\w.-])*)\(((?:\\\/|[\w.-])+)\)\?$/.exec(body);
  if (optional) {
    const base = optional[1].replace(/\\\//g, "/");
    const rest = optional[2].replace(/\\\//g, "/");
    return [
      { exact: true, path: base },
      { exact: anchored, path: base + rest },
    ];
  }

  if (!/^(?:\\\/|[\w.-])+$/.test(body)) return null;
  return [{ exact: anchored, path: body.replace(/\\\//g, "/") }];
}

const STYLE = /:style\(([^)]*)\)\s*$/;
const REMOVE = /:remove\(\)\s*$/;

const byDomain = new Map();
const skipped = [];
let seen = 0;

for (const raw of readRules()) {
  const line = raw.trim();
  if (!line || line.startsWith("!") || line.startsWith("[")) continue;
  // Cosmetic filters only: domains##selector. Network rules are the DNS layer's
  // job, and #@# exceptions have nothing to translate.
  const m = /^([^#]+)##(.+)$/.exec(line);
  if (!m) continue;
  seen++;

  const [, domains, body] = m;
  let selector = body;
  let declarations = "display: none !important;";
  let paths = null;

  const mp = MATCHES_PATH.exec(selector);
  if (mp) {
    paths = pathConditions(mp[1]);
    if (!paths) { skipped.push(line); continue; }
    selector = selector.slice(mp[0].length);
  }

  const style = STYLE.exec(selector);
  if (style) {
    selector = selector.slice(0, style.index);
    declarations = style[1].trim().replace(/;?$/, ";");
  } else if (REMOVE.test(selector)) {
    selector = selector.replace(REMOVE, "");
  }

  if (UNTRANSLATABLE.test(selector)) {
    skipped.push(line);
    continue;
  }

  for (const domain of domains.split(",").map(d => d.trim()).filter(Boolean)) {
    const cond = paths
      ? paths
          .map(p => `${p.exact ? "url" : "url-prefix"}(https://${domain}${p.path})`)
          .join(", ")
      : `domain(${domain})`;
    if (!byDomain.has(cond)) byDomain.set(cond, []);
    byDomain.get(cond).push([selector.trim(), declarations]);
  }
}

const out = [
  "/* Generated by deploy/gen-usercontent.js -- do not edit by hand. */",
  "/* Source: ublock-social-media-filters.txt */",
  "",
];
for (const [cond, rules] of [...byDomain].sort()) {
  out.push(`@-moz-document ${cond} {`);
  for (const [selector, declarations] of rules) {
    out.push(`  ${selector} { ${declarations} }`);
  }
  out.push("}", "");
}
if (skipped.length) {
  out.push("/* Not translatable to CSS -- these stay uBO-only:", "");
  for (const line of skipped) out.push(` * ${line}`);
  out.push(" */", "");
}
fs.writeFileSync(OUT, out.join("\n"));

const translated = seen - skipped.length;
console.log(`${translated}/${seen} cosmetic rules translated, ${skipped.length} skipped`);
console.log(`wrote ${OUT}`);
